import type { ReadableStream as NodeReadableStream } from 'node:stream/web';
import { createWriteStream } from 'node:fs';
import { mkdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { DatabaseSync } from 'node:sqlite';
import { Readable } from 'node:stream';
import { pipeline } from 'node:stream/promises';
import { fileURLToPath } from 'node:url';
import { styleText } from 'node:util';
import { decompressBzip2File } from './bzip2.js';

const CATALOGS_URL = 'https://github.com/phpcfdi/resources-sat-catalogs/releases/latest/download/catalogs.db.bz2';
const MAX_ALLOW_ROWS = 250;

interface CatalogMeta {
  tableName: string;
  slug: string;
  camelName: string;
  pascalName: string;
  domain: string;
  isKeyValue: boolean;
  keyField?: string;
  textField?: string;
}

function logInfo(message: string): void {
  console.log(`${styleText('cyan', 'info')} ${message}`);
}

function formatDuration(durationMs: number): string {
  if (durationMs < 1000) {
    return `${Math.round(durationMs)}ms`;
  }

  return `${(durationMs / 1000).toFixed(2)}s`;
}

async function runAction(label: string, task: () => Promise<void>): Promise<void> {
  const startedAt = performance.now();
  try {
    await task();
    const duration = formatDuration(performance.now() - startedAt);
    console.log(`${styleText('green', 'DONE')} ${label} ${styleText('dim', `(${duration})`)}`);
  } catch (error) {
    const duration = formatDuration(performance.now() - startedAt);
    console.error(`${styleText('red', 'FAILED')} ${label} ${styleText('dim', `(${duration})`)}`);
    throw error;
  }
}

export function toSnakeCase(value: string): string {
  return value
    .replaceAll(/([\da-z])([A-Z])/g, '$1_$2')
    .replaceAll(/([A-Z]+)([A-Z][a-z])/g, '$1_$2')
    .replaceAll(/[^\da-z]+/gi, '_')
    .replaceAll(/^_+|_+$/g, '')
    .toLowerCase();
}

export function toCamelCase(snake: string): string {
  return snake.replaceAll(/_([\da-z])/g, (_, char: string) => char.toUpperCase());
}

export function toPascalCase(snake: string): string {
  const camel = toCamelCase(snake);

  return camel.charAt(0).toUpperCase() + camel.slice(1);
}

const DOMAIN_PREFIXES: readonly [string, string][] = [
  ['cfdi_40_', 'cfdi-40'],
  ['cfdi_', 'cfdi-33'],
  ['nomina_', 'nomina'],
  ['ccp_31_', 'ccp-31'],
  ['ccp_30_', 'ccp-30'],
  ['ccp_20_', 'ccp-20'],
  ['cce_20_', 'cce-20'],
  ['cce_', 'cce-11'],
  ['ret_20_', 'ret-20'],
  ['pagos_', 'pagos'],
  ['hyp_10_', 'hyp-10'],
];

export function resolveDomain(slug: string): string {
  for (const [prefix, domain] of DOMAIN_PREFIXES) {
    if (slug.startsWith(prefix)) {
      return domain;
    }
  }

  return 'other';
}

function inferFieldTypes(rows: Record<string, unknown>[]): { name: string; tsType: string }[] {
  const typeMap = new Map<string, Set<string>>();

  for (const row of rows) {
    for (const [key, value] of Object.entries(row)) {
      let types = typeMap.get(key);
      if (!types) {
        types = new Set<string>();
        typeMap.set(key, types);
      }

      if (value === null || value === undefined) {
        types.add('null');
      } else if (typeof value === 'number') {
        types.add('number');
      } else if (typeof value === 'boolean') {
        types.add('boolean');
      } else {
        types.add('string');
      }
    }
  }

  return Array.from(typeMap, ([name, types]) => ({
    name,
    tsType: [...types].toSorted((a, b) => a.localeCompare(b)).join(' | '),
  }));
}

function detectKeyValueFields(columns: string[]): { keyField?: string; textField?: string } {
  const colSet = new Set(columns);
  if (colSet.has('id') && colSet.has('texto')) {
    return { keyField: 'id', textField: 'texto' };
  }

  if (colSet.has('estado') && colSet.has('texto')) {
    return { keyField: 'estado', textField: 'texto' };
  }

  if (colSet.has('id') && colSet.has('descripcion')) {
    return { keyField: 'id', textField: 'descripcion' };
  }

  if (colSet.has('id')) {
    return { keyField: 'id', textField: 'id' };
  }

  return {};
}

function formatCatalogModule(meta: CatalogMeta, rows: Record<string, unknown>[]): string {
  const fields = inferFieldTypes(rows);
  const interfaceLines = fields.map((f) => `  readonly ${f.name}: ${f.tsType};`).join('\n');
  const dataJson = JSON.stringify(rows);

  const header = '/* eslint-disable */\n// Auto-generated by scripts/populate_sat_catalogs.ts — do not edit manually.\n';

  if (!meta.isKeyValue) {
    return `${header}
export interface ${meta.pascalName}Item {
${interfaceLines}
}

export const ${meta.camelName}: readonly ${meta.pascalName}Item[] = ${dataJson};
`;
  }

  const configArg
    = meta.keyField === 'id' && meta.textField === 'texto'
      ? ''
      : `, { keyField: '${meta.keyField}', textField: '${meta.textField}' }`;

  return `${header}import { createCatalog } from '../helpers.js';

export interface ${meta.pascalName}Item {
  readonly [key: string]: string | number | boolean | null;
${interfaceLines}
}

export const ${meta.camelName}Data: readonly ${meta.pascalName}Item[] = ${dataJson};

export const ${meta.camelName} = createCatalog<${meta.pascalName}Item>(${meta.camelName}Data${configArg});
`;
}

async function downloadFile(url: string, outputPath: string): Promise<void> {
  const response = await fetch(url);
  if (!response.ok || !response.body) {
    throw new Error(`Failed to download ${url}: HTTP ${response.status} ${response.statusText}`);
  }

  await pipeline(
    Readable.fromWeb(response.body as NodeReadableStream<Uint8Array>),
    createWriteStream(outputPath),
  );
}

async function generateCatalogModules(
  catalogsDbPath: string,
  srcPath: string,
): Promise<CatalogMeta[]> {
  const catalogsPath = path.join(srcPath, 'catalogs');
  const domainsPath = path.join(srcPath, 'domains');

  await rm(catalogsPath, { force: true, recursive: true });
  await rm(domainsPath, { force: true, recursive: true });
  await mkdir(catalogsPath, { recursive: true });
  await mkdir(domainsPath, { recursive: true });

  const db = new DatabaseSync(catalogsDbPath, { readOnly: true });
  const generated: CatalogMeta[] = [];

  try {
    const allTables = db
      .prepare("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name")
      .all() as { name: string }[];

    logInfo(`Found ${allTables.length} tables`);

    for (const table of allTables) {
      const quotedTable = `"${table.name.replaceAll('"', '""')}"`;
      const countSql = ['SELECT COUNT(*) AS count FROM', quotedTable].join(' ');
      const countResult = db.prepare(countSql).get() as { count: number };
      if (countResult.count === 0 || countResult.count > MAX_ALLOW_ROWS) {
        continue;
      }

      const selectSql = ['SELECT * FROM', quotedTable].join(' ');
      const rows = db.prepare(selectSql).all() as Record<string, unknown>[];
      const slug = toSnakeCase(table.name);
      const columns = rows.length > 0 ? Object.keys(rows[0]) : [];
      const { keyField, textField } = detectKeyValueFields(columns);

      const meta: CatalogMeta = {
        tableName: table.name,
        slug,
        camelName: toCamelCase(slug),
        pascalName: toPascalCase(slug),
        domain: resolveDomain(slug),
        isKeyValue: Boolean(keyField && textField),
        keyField,
        textField,
      };

      const moduleContent = formatCatalogModule(meta, rows);
      await writeFile(path.join(catalogsPath, `${slug}.ts`), moduleContent);
      generated.push(meta);
    }

    logInfo(`Generated ${generated.length} catalog modules (<= ${MAX_ALLOW_ROWS} rows)`);
  } finally {
    db.close();
  }

  const byDomain = Map.groupBy(generated, (meta) => meta.domain);
  const sortedDomains = [...byDomain].toSorted(([a], [b]) => a.localeCompare(b));

  const header = '/* eslint-disable */\n// Auto-generated by scripts/populate_sat_catalogs.ts — do not edit manually.\n';

  for (const [domain, items] of sortedDomains) {
    const lines = [
      header,
      "export { createCatalog, SatCatalog } from '../helpers.js';",
      "export type { SatCatalogConfig, SatCatalogOption, SatCatalogOptionsConfig, SatCatalogRecord } from '../types.js';",
      '',
      ...items.map((item) => `export * from '../catalogs/${item.slug}.js';`),
      '',
    ];
    await writeFile(path.join(domainsPath, `${domain}.ts`), lines.join('\n'));
  }

  const indexLines = [
    header,
    "export { createCatalog, SatCatalog } from './helpers.js';",
    "export type { SatCatalogConfig, SatCatalogOption, SatCatalogOptionsConfig, SatCatalogRecord } from './types.js';",
    '',
    ...generated.map((item) => `export * from './catalogs/${item.slug}.js';`),
    '',
  ];
  await writeFile(path.join(srcPath, 'index.ts'), indexLines.join('\n'));

  return generated;
}

export async function run(): Promise<void> {
  const rootPath = path.resolve(import.meta.dirname, '..');
  const srcPath = path.join(rootPath, 'src');
  const tmpPath = path.join(rootPath, 'tmp');
  const bz2Path = path.join(tmpPath, 'catalogs.db.bz2');
  const dbPath = path.join(tmpPath, 'catalogs.db');

  await rm(tmpPath, { force: true, recursive: true });
  await mkdir(tmpPath, { recursive: true });

  try {
    await runAction('Downloading catalogs.db.bz2', async () => {
      await downloadFile(CATALOGS_URL, bz2Path);
    });

    await runAction('Decompressing catalogs.db.bz2', async () => {
      await decompressBzip2File(bz2Path, dbPath);
    });

    await runAction('Generating TypeScript catalog modules', async () => {
      await generateCatalogModules(dbPath, srcPath);
    });
  } finally {
    await rm(tmpPath, { force: true, recursive: true });
  }
}

const isDirectExecution
  = Boolean(process.argv[1]) && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isDirectExecution) {
  try {
    await run();
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
